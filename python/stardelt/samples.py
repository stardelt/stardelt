"""`stardelt samples load trips`: the one sample table every guide can use (#1816).

The rows are generated by the platform's engine and written as the caller, into
`<catalog>.samples.<name>`. The call is idempotent, so running it twice is harmless.
"""

from __future__ import annotations

from stardelt.api import Client

SAMPLES = ("trips",)


def load(name, catalog=None, client=None):
    """Load a sample as the signed-in person; returns Nova's answer.

    ``created`` is true the first time and false when the table is already there; ``rows`` is
    the row count after the call. Raises ``ValueError`` for a name this client does not know,
    and ``stardelt.api.StardeltApiError`` when the platform refuses (no create right in that
    catalog, no such catalog, or the engine failed).
    """
    if name not in SAMPLES:
        raise ValueError(f"no such sample: {name} — the samples are: {', '.join(SAMPLES)}")
    query = {"catalog": catalog} if catalog else None
    return (client or Client()).call("samples_load", path={"name": name}, query=query)
